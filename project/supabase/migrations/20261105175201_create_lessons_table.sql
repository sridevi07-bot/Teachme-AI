/*
# Create lessons table

1. New Tables
- `lessons`
  - `id` (uuid, primary key) - unique lesson identifier
  - `topic` (text, not null) - the subject the student asked about
  - `title` (text, not null) - lesson title generated by the AI
  - `content` (jsonb, not null) - structured lesson: introduction, sections, steps, summary
  - `created_at` (timestamptz) - when the lesson was generated

2. Security
- Enable row level security on `lessons`.
- Grant SELECT and INSERT to `anon` and `authenticated` so the app can list and revisit lessons. The app has no sign-in, so it runs as `anon`.
- Policies allow reading and inserting lessons. Lessons are intentionally shared within this personal app; there is no update or delete from the browser.

3. Notes
- Indexed on `created_at` so the recently studied list loads quickly.
*/

CREATE TABLE IF NOT EXISTS lessons (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  topic text NOT NULL,
  title text NOT NULL,
  content jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS lessons_created_at_idx ON lessons (created_at DESC);

ALTER TABLE lessons ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON lessons TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_lessons" ON lessons;
CREATE POLICY "anon_select_lessons" ON lessons FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_lessons" ON lessons;
CREATE POLICY "anon_insert_lessons" ON lessons FOR INSERT
  TO anon, authenticated WITH CHECK (true);
